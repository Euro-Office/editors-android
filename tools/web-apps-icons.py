# Shapes drawn point by point, which one tap can't insert
SKIPPED_SHAPES = {"spline", "polyline1", "polyline2"}


def snake(name):
    name = re.sub(r"([a-z])([A-Z0-9])", r"\1_\2", name)
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def number(value):
    return "%g" % round(value, 3)


def element_path(element):
    tag = element.tag.replace(SVG, "")
    attr = element.attrib.get
    if tag == "path":
        return attr("d")
    if tag == "rect":
        x, y = float(attr("x", 0)), float(attr("y", 0))
        w, h = float(attr("width")), float(attr("height"))
        return "M%s,%sh%sv%sh%sz" % (number(x), number(y), number(w), number(h), number(-w))
    if tag == "circle":
        cx, cy, r = float(attr("cx")), float(attr("cy")), float(attr("r"))
        return "M%s,%sa%s,%s 0,1 1,%s,0a%s,%s 0,1 1,%s,0z" % (
            number(cx - r), number(cy), number(r), number(r), number(2 * r), number(r), number(r), number(-2 * r))
    return None


def paths(element, opacity=1.0):
    """The drawable paths of a symbol: (pathData, fill alpha, evenOdd, stroke width or None)."""
    result = []
    for child in element:
        tag = child.tag.replace(SVG, "")
        own = opacity * float(child.attrib.get("opacity", 1))
        if tag == "g":
            result += paths(child, own)
            continue
        data = element_path(child)
        if not data:
            continue
        stroke = child.attrib.get("stroke")
        width = float(child.attrib.get("stroke-width", 1)) if stroke and stroke != "none" else None
        filled = child.attrib.get("fill") != "none"
        result.append((data, own, child.attrib.get("fill-rule") == "evenodd", filled, width))
    return result


def vector(symbol, size, mirrored=False):
    view = (symbol.attrib.get("viewBox") or "0 0 40 40").split()
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- %s -->" % LICENSE,
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="%ddp"' % size, '    android:height="%ddp"' % size,
             '    android:viewportWidth="%s"' % view[2], '    android:viewportHeight="%s"' % view[3]]
    if mirrored:
        lines.append('    android:autoMirrored="true"')
    lines.append('    android:tint="@color/editors_icon">')
    for data, alpha, even_odd, filled, stroke in paths(symbol):
        lines.append("    <path")
        if filled:
            lines.append('        android:fillColor="@android:color/white"')
            if alpha < 1:
                lines.append('        android:fillAlpha="%s"' % number(alpha))
            if even_odd:
                lines.append('        android:fillType="evenOdd"')
        if stroke:
            lines += ['        android:strokeColor="@android:color/white"', '        android:strokeWidth="%s"' % number(stroke),
                      '        android:strokeLineCap="round"', '        android:strokeLineJoin="round"']
        lines.append('        android:pathData="%s" />' % " ".join(data.split()))
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def symbols(path):
    tree = ET.parse(path)
    return {s.attrib["id"]: s for s in tree.iter(SVG + "symbol")}


def js_texts(source):
    return dict(re.findall(r"\b(text[A-Za-z0-9]+)\s*:\s*'([^']*)'", source))


def xml_text(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"'))


def menu_icons(web_apps):
    """The menu icons (MENU_ICONS); mirrored right to left where web-apps has an -rtl variant."""
    for name, path in MENU_ICONS.items():
        source = os.path.join(web_apps, "apps", path)
        mirrored = os.path.exists(source.replace(".svg", "-rtl.svg"))
        with open(os.path.join(DRAWABLES, "ic_editor_%s.xml" % name), "w", encoding="utf-8") as out:
            out.write(vector(ET.parse(source).getroot(), 24, mirrored))
    print("%d menu icons" % len(MENU_ICONS))


def two_tone_vector(symbol):
    """A toolbar symbol: strokes and fills as the symbol and its paths set them, blue parts in the accent."""
    view = symbol.attrib["viewBox"].split()
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- %s -->" % LICENSE,
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp"', '    android:height="24dp"',
             '    android:viewportWidth="%s"' % view[2], '    android:viewportHeight="%s">' % view[3]]

    def walk(element, inherited):
        for child in element:
            attrs = dict(inherited)
            attrs.update({k: v for k, v in child.attrib.items() if k in ("stroke", "fill", "stroke-width", "class", "fill-rule")})
            if child.tag.replace(SVG, "") == "g":
                walk(child, attrs)
                continue
            data = element_path(child)
            if not data:
                continue
            kind = attrs.get("class", "")
            color = "@color/editors_accent" if "blue" in kind else "@color/editors_icon"
            alpha = "0.45" if "secondary" in kind else None
            lines.append("    <path")
            if attrs.get("fill", "black") != "none":
                lines.append('        android:fillColor="%s"' % color)
                if alpha:
                    lines.append('        android:fillAlpha="%s"' % alpha)
                if attrs.get("fill-rule") == "evenodd":
                    lines.append('        android:fillType="evenOdd"')
            if attrs.get("stroke", "none") != "none":
                lines.extend(['        android:strokeColor="%s"' % color, '        android:strokeWidth="%s"' % attrs.get("stroke-width", "1"),
                              '        android:strokeLineCap="round"', '        android:strokeLineJoin="round"'])
                if alpha:
                    lines.append('        android:strokeAlpha="%s"' % alpha)
            lines.append('        android:pathData="%s" />' % " ".join(data.split()))

    walk(symbol, {k: v for k, v in symbol.attrib.items() if k in ("stroke", "fill", "stroke-width")})
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def format_icons(web_apps):
    """The format panels' icons (FORMAT_ICONS)."""
    sprites = {}
    for name, (editor, symbol) in FORMAT_ICONS.items():
        if editor not in sprites:
            sprites[editor] = symbols(os.path.join(web_apps, "apps", SPRITE % editor))
        with open(os.path.join(DRAWABLES, "ic_editor_%s.xml" % name), "w", encoding="utf-8") as out:
            out.write(two_tone_vector(sprites[editor][symbol]))
    print("%d format icons" % len(FORMAT_ICONS))


def main(web_apps, sdkjs):
    menu_icons(web_apps)
    format_icons(web_apps)
    toolbar = os.path.join(web_apps, "apps/common/main/resources/img/toolbar")
    strings = []  # (name, English text)

    # Chart types: web-apps' groups and entries (Common.define.chartData)
    define = open(os.path.join(web_apps, "apps/common/main/lib/util/define.js"), encoding="utf-8").read()
    texts = js_texts(define)
    groups = re.findall(r"\{id: '(menu-chart-group-[a-z]+)', caption: this\.(text[A-Za-z]+)", define)
    entries = re.findall(r"group: '(menu-chart-group-[a-z]+)',\s*type: Asc\.c_oAscChartTypeSettings\.([A-Za-z0-9]+),"
                         r"\s*iconCls: '([a-z0-9-]+)', tip: this\.(text[A-Za-z0-9]+)", define)
    chart_icons = symbols(os.path.join(toolbar, "charttypes.svg"))
    charts = []
    for group, caption in groups:
        items = []
        for entry_group, type_name, icon, tip in entries:
            if entry_group != group or type_name not in CHART_TYPES:
                continue
            name = snake(icon)
            with open(os.path.join(DRAWABLES, "editors_chart_%s.xml" % name), "w") as f:
                f.write(vector(chart_icons["chart-" + icon], 40))
            strings.append(("editors_chart_type_" + name, texts[tip]))
            items.append((CHART_TYPES[type_name], name))
        if items:
            group_name = snake(group.replace("menu-chart-group-", ""))
            strings.append(("editors_chart_group_" + group_name, texts[caption]))
            charts.append((group_name, items))

    # Shapes: sdkjs' groups, web-apps' pictures and names
    settings = open(os.path.join(sdkjs, "common/Shapes/EditorSettings.js"), encoding="utf-8").read()
    group_names = re.findall(r'"([^"]+)"', settings[settings.index("g_oAutoShapesGroups"):settings.index("var autoShapes")])
    lists = settings[settings.index("var autoShapes"):settings.index("var g_oAutoShapesTypes")]
    presets = [re.findall(r'"([A-Za-z0-9]+)"', block) for block in re.findall(r"\[([^\[\]]+)\]", lists)]
    locale = json.load(open(os.path.join(web_apps, "apps/documenteditor/main/locale/en.json"), encoding="utf-8"))
    group_texts = ["txtBasicShapes", "txtFiguredArrows", "txtMath", "txtCharts", "txtStarsRibbons", "txtCallouts",
                   "txtButtons", "txtRectangles", "txtLines"]
    shape_icons = symbols(os.path.join(toolbar, "shapetypes.svg"))
    shapes = []
    for index, group in enumerate(group_names):
        items = []
        for preset in presets[index]:
            if preset in SKIPPED_SHAPES:
                continue
            name = snake(preset)
            with open(os.path.join(DRAWABLES, "editors_shape_%s.xml" % name), "w") as f:
                f.write(vector(shape_icons["svg-icon-" + preset], 24))
            label = "editors_shape_name_" + name
            if label not in dict(strings):
                strings.append((label, locale["DE.Controllers.Main.txtShape_" + preset]))
            items.append((preset, name))
        group_name = snake(group_texts[index][3:])
        strings.append(("editors_shape_group_" + group_name, locale["DE.Controllers.Main." + group_texts[index]]))
        shapes.append((group_name, items))

    # SmartArt: web-apps' groups and layouts (Common.define.smartArt); the layouts by sdkjs' types
    # and their definition files
    cache = open(os.path.join(sdkjs, "common/SmartArts/SmartArtCache.js"), encoding="utf-8").read()
    files = dict(re.findall(r'c_oAscSmartArtTypesToNameBinRelationShip\[Asc\.c_oAscSmartArtTypes\.(\w+)\] = "([^"]+)"', cache))
    defines = open(os.path.join(sdkjs, "common/commonDefines.js"), encoding="utf-8").read()
    types_block = defines[defines.index("var c_oAscSmartArtTypes = {"):]
    smart_types = dict((n, int(v)) for n, v in re.findall(r"(\w+)\s*:\s*(\d+)", types_block[:types_block.index("}")]))
    smart_data = define[define.index("getSmartArtData"):]
    smart_data = smart_data[:smart_data.index("];")]
    smart_arts = []
    for group, caption, items_text in re.findall(
            r"id: 'menu-smart-art-group-([a-z]+)',.*?caption: this\.(text\w+),.*?items: \[(.*?)\]", smart_data, re.S):
        items = []
        for type_name, tip in re.findall(r"type: Asc\.c_oAscSmartArtTypes\.(\w+), tip: this\.(text\w+)", items_text):
            name = snake(files[type_name])
            if not os.path.exists(os.path.join(PREVIEWS, "editors_smartart_%s.webp" % name)):
                continue
            label = "editors_smartart_name_" + name
            if label not in dict(strings):
                strings.append((label, texts[tip]))
            items.append((smart_types[type_name], files[type_name], name))
        if items:
            strings.append(("editors_smartart_group_" + group, texts[caption]))
            smart_arts.append((group, items))

    # The names, in a block of strings.xml (translated with the others)
    begin, end = "    <!-- Insert pickers (tools/web-apps-icons.py) -->\n", "    <!-- End of the insert pickers -->\n"
    block = begin + "".join('    <string name="%s">%s</string>\n' % (n, xml_text(t)) for n, t in strings) + end
    source = open(STRINGS, encoding="utf-8").read()
    if begin in source:
        source = source[:source.index(begin)] + block + source[source.index(end) + len(end):]
    else:
        source = source.replace("</resources>", block + "</resources>")
    open(STRINGS, "w", encoding="utf-8").write(source)

    # The catalog
    out = ["// Generated by tools/web-apps-icons.py from web-apps' and sdkjs' insert menus: don't edit",
           "package lib.editors.gbase.ui.activities", "", "import lib.editors.resources.R as Resources", "",
           "/**",
           " * What the insert pickers offer, in groups: chart types (Asc.c_oAscChartTypeSettings), shapes",
           " * (presets) and SmartArt layouts.",
           " */",
           "internal object InsertCatalog {", "",
           "    class Item<T>(val value: T, val icon: Int, val label: Int)", "",
           "    class Group<T>(val label: Int, val items: List<Item<T>>)", "",
           "    /** A SmartArt layout: its type (Asc.c_oAscSmartArtTypes) and definition file (sdkjs' SmartArtData). */",
           "    data class SmartArt(val type: Int, val file: String)", "",
           "    val CHARTS: List<Group<Int>> = listOf("]
    out.append(",\n".join(
        "        Group(Resources.string.editors_chart_group_%s, listOf(\n%s\n        ))" % (group, ",\n".join(
            "            Item(%d, Resources.drawable.editors_chart_%s, Resources.string.editors_chart_type_%s)" % (t, n, n)
            for t, n in items)) for group, items in charts))
    out += ["    )", "", "    val SHAPES: List<Group<String>> = listOf("]
    out.append(",\n".join(
        "        Group(Resources.string.editors_shape_group_%s, listOf(\n%s\n        ))" % (group, ",\n".join(
            '            Item("%s", Resources.drawable.editors_shape_%s, Resources.string.editors_shape_name_%s)' % (p, n, n)
            for p, n in items)) for group, items in shapes))
    out += ["    )", "", "    val SMART_ARTS: List<Group<SmartArt>> = listOf("]
    out.append(",\n".join(
        "        Group(Resources.string.editors_smartart_group_%s, listOf(\n%s\n        ))" % (group, ",\n".join(
            '            Item(SmartArt(%d, "%s"), Resources.drawable.editors_smartart_%s, Resources.string.editors_smartart_name_%s)'
            % (t, f, n, n) for t, f, n in items)) for group, items in smart_arts))
    out += ["    )", "}", ""]
    open(CATALOG, "w", encoding="utf-8").write("\n".join(out))
    print("%d chart types, %d shapes, %d SmartArt layouts" % (sum(len(i) for _, i in charts), sum(len(i) for _, i in shapes),
                                                            sum(len(i) for _, i in smart_arts)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
